export const featuredTestimonials = sampleTestimonials.filter(testimonial => testimonial.featured);

export const verifiedTestimonials = sampleTestimonials.filter(testimonial => testimonial.verified);

export const getTestimonialsByRating = (rating) => {
  return sampleTestimonials.filter(testimonial => testimonial.rating === rating);
};

export const getTestimonialsByAgent = (agentName) => {
  return sampleTestimonials.filter(testimonial => 
    testimonial.agent.name.toLowerCase().includes(agentName.toLowerCase())
  );
};

export const getTestimonialsByProperty = (propertyId) => {
  return sampleTestimonials.filter(testimonial => 
    testimonial.property && testimonial.property.id === propertyId
  );
};

export const getTestimonialsByLocation = (location) => {
  return sampleTestimonials.filter(testimonial => 
    testimonial.location.toLowerCase().includes(location.toLowerCase())
  );
};

export const getTestimonialsByRole = (role) => {
  return sampleTestimonials.filter(testimonial => 
    testimonial.role.toLowerCase().includes(role.toLowerCase())
  );
};

export const getTestimonialsByDateRange = (startDate, endDate) => {
  return sampleTestimonials.filter(testimonial => 
    testimonial.date >= startDate && testimonial.date <= endDate
  );
};

export const getRecentTestimonials = (limit = 5) => {
  return sampleTestimonials
    .sort((a, b) => b.date - a.date)
    .slice(0, limit);
};

export const getTestimonialStats = () => {
  const totalTestimonials = sampleTestimonials.length;
  const averageRating = sampleTestimonials.reduce((sum, t) => sum + t.rating, 0) / totalTestimonials;
  const fiveStarCount = getTestimonialsByRating(5).length;
  const verifiedCount = verifiedTestimonials.length;
  const featuredCount = featuredTestimonials.length;

  return {
    totalTestimonials,
    averageRating: Math.round(averageRating * 10) / 10,
    fiveStarCount,
    fiveStarPercentage: Math.round((fiveStarCount / totalTestimonials) * 100),
    verifiedCount,
    featuredCount
  };
};

export const searchTestimonials = (filters = {}) => {
  let results = [...sampleTestimonials];

  if (filters.rating) {
    results = results.filter(testimonial => testimonial.rating === filters.rating);
  }

  if (filters.location) {
    results = results.filter(testimonial => 
      testimonial.location.toLowerCase().includes(filters.location.toLowerCase())
    );
  }

  if (filters.role) {
    results = results.filter(testimonial => 
      testimonial.role.toLowerCase().includes(filters.role.toLowerCase())
    );
  }

  if (filters.verified) {
    results = results.filter(testimonial => testimonial.verified);
  }

  if (filters.featured) {
    results = results.filter(testimonial => testimonial.featured);
  }

  if (filters.agent) {
    results = results.filter(testimonial => 
      testimonial.agent.name.toLowerCase().includes(filters.agent.toLowerCase())
    );
  }

  if (filters.property) {
    results = results.filter(testimonial => 
      testimonial.property && testimonial.property.title.toLowerCase().includes(filters.property.toLowerCase())
    );
  }

  if (filters.startDate && filters.endDate) {
    results = results.filter(testimonial => 
      testimonial.date >= filters.startDate && testimonial.date <= filters.endDate
    );
  }

  return results;
};